CREATE TABLE clientes (
  id_cliente	INT 			NOT NULL,
  nombre		VARCHAR(100)	NOT NULL,
  email			VARCHAR(150),
  ciudad		VARCHAR(100),
  segmento      VARCHAR(50),
  fecha_registro DATE,
  CONSTRAINT PK_clientes PRIMARY KEY (id_cliente)
  );

CREATE TABLE productos (
  id_producto	  INT 			NOT NULL,
  nombre_producto VARCHAR(150)	NOT NULL,
  categoria		  VARCHAR(100),
  subcategoria	  VARCHAR(100),
  precio		  DECIMAL(10,2) NOT NULL,
  costo			  DECIMAL(10,2) NOT NULL,
  CONSTRAINT PK_productos PRIMARY KEY (id_producto)
  );

CREATE TABLE territorios (
  id_territorio  INT 			NOT NULL,
  region		  VARCHAR(100)	NOT NULL,
  pais			  VARCHAR(100),
  zona			  VARCHAR(100),
  CONSTRAINT PK_territorios PRIMARY KEY (id_territorio)
  );

CREATE TABLE ventas (
  id_venta		INT				NOT NULL,
  fecha_venta	DATE			NOT NULL,
  id_cliente	INT 			NOT NULL,
  id_producto	INT 			NOT NULL,
  id_territorio INT             NOT NULL,
  cantidad		INT             NOT NULL,
  total_venta	DECIMAL(10,2)	NOT NULL,
  canal			VARCHAR(50)     NOT NULL,
  CONSTRAINT PK_ventas PRIMARY KEY (id_venta),
  CONSTRAINT FK_ventas_clientes FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
  CONSTRAINT FK_ventas_productos FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
  CONSTRAINT FK_ventas_territorios FOREIGN KEY (id_territorio) REFERENCES territorios(id_territorio)
  );


